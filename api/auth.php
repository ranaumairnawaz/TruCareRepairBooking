<?php
/**
 * auth.php — Minimal HS256 JWT sign/verify + bcrypt admin auth helpers
 *
 * No Composer dependency required for this part - the JWT implementation
 * is a small, self-contained HS256 signer/verifier.
 */

require_once __DIR__ . '/../config.php';
require_once __DIR__ . '/helpers.php';

/**
 * Ensures the user is logged in as admin via PHP sessions.
 */
function requireAdmin(): void
{
    startAppSession();
    if (empty($_SESSION['admin_logged_in'])) {
        jsonResponse(['error' => 'Unauthorized: missing or invalid session, please log in again'], 401);
    }
}

/**
 * bcrypt verify — compatible with hashes generated by bcryptjs (Node) since
 * both implement the same $2a$/$2b$ bcrypt format.
 */
function checkPassword(string $plain, string $hash): bool
{
    return password_verify($plain, $hash);
}

/**
 * POST /api/admin/login — username + password → PHP Session.
 */
function handleAdminLogin(): void
{
    if (!rateLimit('admin_login', 15 * 60, 10)) {
        jsonResponse(['error' => 'Too many login attempts. Please try again later.'], 429);
    }

    require_once __DIR__ . '/db.php';

    $body = getJsonBody();
    $username = isset($body['username']) ? trim((string) $body['username']) : '';
    $password = $body['password'] ?? null;

    if ($username === '' || !is_string($password) || $password === '') {
        jsonResponse(['success' => false, 'error' => 'Username and password are required'], 400);
    }

    if (strlen($username) > 64 || !preg_match('/^[a-zA-Z0-9._-]+$/', $username)) {
        jsonResponse(['success' => false, 'error' => 'Invalid username or password'], 401);
    }

    $admin = getAdminByUsername($username);
    if (!$admin || !checkPassword($password, $admin['password_hash'])) {
        jsonResponse(['success' => false, 'error' => 'Invalid username or password'], 401);
    }

    startAppSession();
    $_SESSION['admin_logged_in'] = true;
    $_SESSION['admin_username'] = $admin['username'];
    jsonResponse([
        'success' => true,
        'username' => $admin['username'],
    ]);
}

/** @deprecated Use handleAdminLogin — kept for backward compatibility */
function handleAdminVerify(): void
{
    handleAdminLogin();
}

/**
 * POST /api/admin/logout — clear admin session.
 */
function handleAdminLogout(): void
{
    startAppSession();
    unset($_SESSION['admin_logged_in'], $_SESSION['admin_username']);
    jsonResponse(['success' => true]);
}
